#!/usr/bin/env python3
"""Render the home social card (build/assets/cards/home.png) from build/assets/home-card/card.html.

usage: python3 build/home_card.py [--port <devtools port, default 9462>]

The home card is "The whole chain" (chosen by the owner on 25 October 2026): the wordmark, "How AI chips are made" and the
subtitle centered in Fraunces on white, over the fifteen stage specimens in the order a chip is made. card.html is
self-contained (the drawings are inlined) and is generated by qa/design3/cards/chain/build.py, which reads the stage
order from content/ and the drawings from the redesign's specimen renders. LinkedIn crops a link's image to about
1.5:1 when the link sits in a comment and to a square in some thumbnails, both from the center, so the wordmark,
title and subtitle sit inside the middle 630 px. build/cards.py skips the home slug so it never overwrites this card.
"""
import os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
port = sys.argv[sys.argv.index('--port') + 1] if '--port' in sys.argv else '9462'
sys.argv = [sys.argv[0]]; sys.path.insert(0, os.path.join(ROOT, 'build'))
import cards  # noqa: E402  (for shrink and LIMIT)
src = os.path.join(ROOT, 'build', 'assets', 'home-card', 'card.html')
out = os.path.join(ROOT, 'build', 'assets', 'cards', 'home.png')
subprocess.run(['python3', os.path.join(ROOT, 'build', 'shoot.py'), 'file://' + src, out, '--width', '1200', '--height', '630', '--wait', '3', '--port', port],
               check=True, stdout=subprocess.DEVNULL)
size = cards.shrink(out)
for n in (128, 96, 64):  # fewer palette colors if the stipple drawings push the card over the limit
    if size <= cards.LIMIT: break
    size = cards.shrink(out, colors=n)
print('wrote %s, %d KB%s' % (out, size // 1024, '' if size <= cards.LIMIT else ' (over the 150 KB limit)'))
